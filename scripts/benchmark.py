"""Measure streaming throughput and latency at several simulator speeds.

For each speed the stack is restarted with SIM_SPEED=<speed>, left to warm up,
then /api/pipeline is sampled for the measurement window. Median
processedRowsPerSecond per query, p95 end-to-end latency and the worst offset
lag are written to docs/benchmarks.md as a Markdown table.

    python scripts/benchmark.py --speeds 1 10 50 100 --minutes 3
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import subprocess
import time
import urllib.request
from pathlib import Path

API = os.environ.get("API", "http://localhost:8000")
QUERIES = ["j1_clean", "j2_flight_state", "j3_traffic", "j4_predict"]
OUT = Path(__file__).resolve().parent.parent / "docs" / "benchmarks.md"


def fetch(path: str) -> dict:
    with urllib.request.urlopen(f"{API}{path}", timeout=10) as resp:
        return json.load(resp)


def restart(speed: float) -> None:
    env = {**os.environ, "SIM_SPEED": str(speed), "ADSB_PROVIDER": "synthetic"}
    subprocess.run(["docker", "compose", "up", "-d", "--force-recreate", "adsb-producer", "metar-producer"], check=True, env=env)


def measure(minutes: float) -> dict:
    samples: dict[str, list[float]] = {q: [] for q in QUERIES}
    lag = 0.0
    p95: list[float] = []
    end = time.time() + minutes * 60
    while time.time() < end:
        try:
            data = fetch("/api/pipeline")
        except OSError:
            time.sleep(5)
            continue
        for q in QUERIES:
            rows = data["queries"].get(q) or []
            if rows and rows[-1].get("processedRowsPerSecond") is not None:
                samples[q].append(float(rows[-1]["processedRowsPerSecond"]))
            if rows and rows[-1].get("maxOffsetsBehindLatest") is not None:
                lag = max(lag, float(rows[-1]["maxOffsetsBehindLatest"]))
        if data["dq"].get("latency_ms_p95") is not None:
            p95.append(float(data["dq"]["latency_ms_p95"]))
        time.sleep(5)
    return {
        "median_rps": {q: round(statistics.median(v), 1) if v else None for q, v in samples.items()},
        "p95_latency_ms": round(max(p95), 0) if p95 else None,
        "max_lag": lag,
    }


def render(results: dict[float, dict], minutes: float) -> str:
    head = "| Speed | " + " | ".join(f"{q} rows/s" for q in QUERIES) + " | p95 latency (ms) | max offsets behind |"
    sep = "|" + "---|" * (len(QUERIES) + 3)
    lines = [
        "# Benchmarks",
        "",
        f"Synthetic simulator replayed at each speed for {minutes:g} minutes after a 60 s warm-up.",
        "Median `processedRowsPerSecond` per streaming query, worst p95 end-to-end latency and",
        "worst Kafka offset lag. Generated by `scripts/benchmark.py`.",
        "",
        head,
        sep,
    ]
    for speed, r in results.items():
        cells = [str(r["median_rps"][q]) for q in QUERIES]
        lines.append(f"| {speed:g}x | " + " | ".join(cells) + f" | {r['p95_latency_ms']} | {r['max_lag']:g} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--speeds", type=float, nargs="+", default=[1, 10, 50, 100])
    ap.add_argument("--minutes", type=float, default=3)
    ap.add_argument("--warmup", type=float, default=60)
    args = ap.parse_args()

    results: dict[float, dict] = {}
    for speed in args.speeds:
        print(f"== {speed:g}x ==")
        restart(speed)
        time.sleep(args.warmup)
        results[speed] = measure(args.minutes)
        print(results[speed])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(results, args.minutes), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
